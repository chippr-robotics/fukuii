package com.chipprbots.ethereum.ephemery

/** Renders the chain configuration fukuii reads for one Ephemery iteration (the HOCON of `custom-chains-dir`).
  *
  * The text is the one `scripts/ephemery/fetch-genesis.sh` wrote before spec 028, plus the two spec 024 keys inside the
  * chain object (`consensus` and `genesis-hash`, spec 028 R14), and a golden test holds it byte for byte against the
  * committed fixtures `src/test/resources/ephemery/ephemery-16x/`. A change of the rendered output is therefore always
  * a reviewed fixture diff.
  *
  * Pure: no `Config`, no clock, no file.
  */
object ChainConfRenderer:

  /** The repository releases come from; the `# Source:` comment of the file links to its release page. */
  val SourceBase: String = "https://github.com/ephemery-testnet/ephemery-genesis"

  /** What the file states about one iteration.
    *
    * @param blobSchedule
    *   the `blobSchedule` entries as (fork, target, max, baseFeeUpdateFraction), in the order they are written
    * @param bootnodes
    *   the execution-layer `enode://` URLs, already checked to hold nothing HOCON could read as syntax
    * @param publishedHash
    *   the published genesis block hash, `0x` and 64 lowercase hex digits
    */
  final case class Params(
      release: String,
      chainId: BigInt,
      genesisTimestamp: Long,
      resetInterval: Long,
      shanghai: Long,
      cancun: Long,
      prague: Long,
      osaka: Option[Long],
      bpo1: Option[Long],
      bpo2: Option[Long],
      amsterdam: Option[Long],
      blobSchedule: Seq[(String, BigInt, BigInt, BigInt)],
      depositContract: String,
      bootnodes: Seq[String],
      publishedHash: String
  )

  /** The blob forks, in the order their entries are written. */
  val BlobForks: List[String] = List("cancun", "prague", "osaka", "bpo1", "bpo2", "amsterdam")

  private def ts(value: Option[Long]): String = value.fold("null")(_.toString)

  private def blobSchedule(p: Params): String =
    BlobForks
      .flatMap(fork => p.blobSchedule.find(_._1 == fork))
      .map { case (fork, target, max, fraction) =>
        s"    $fork { target = $target, max = $max, base-fee-update-fraction = $fraction }\n"
      }
      .mkString

  /** One quoted URL per line, each but the last followed by a comma; an empty list is one empty line. */
  private def bootnodes(p: Params): String =
    if p.bootnodes.isEmpty then "\n"
    else p.bootnodes.map(n => s"    \"$n\"").mkString("", ",\n", "\n")

  def render(p: Params): String =
    s"""{
  # GENERATED by scripts/ephemery/fetch-genesis.sh from ${p.release} — do not edit; re-run the script.
  # Source: ${ChainConfRenderer.SourceBase}/releases/tag/${p.release} (genesis.json config, enodes.txt).
  # Ephemery resets every ${p.resetInterval} s; the next iteration has a new chain id, genesis and
  # timestamps, so this file is valid for ${p.release} only.
  # Published genesis block hash: ${p.publishedHash}
  network-id = ${p.chainId}
  chain-id = "0x${p.chainId.toString(16)}"
  network-type = "eth"
  consensus = "engine-api"
  genesis-hash = "${p.publishedHash}"

  # Merged at genesis (terminalTotalDifficulty 0).
  terminal-total-difficulty = "0"

  # Timestamp forks (EIP-6122), verbatim from genesis.json config.*Time. Forks at or before the genesis
  # timestamp (${p.genesisTimestamp}) are part of the genesis ruleset and are not fork-id checksum entries.
  shanghai-timestamp = ${ts(Some(p.shanghai))}
  cancun-timestamp = ${ts(Some(p.cancun))}
  prague-timestamp = ${ts(Some(p.prague))}
  osaka-timestamp = ${ts(p.osaka)}
  bpo1-timestamp = ${ts(p.bpo1)}
  bpo2-timestamp = ${ts(p.bpo2)}
  amsterdam-timestamp = ${ts(p.amsterdam)}

  # EIP-7840 blob schedule, verbatim from genesis.json config.blobSchedule (target and max blobs per
  # block, blob base-fee update fraction), each entry in force from its fork's timestamp above.
  blob-schedule {
${blobSchedule(p)}  }

  merge-netsplit-block-number = "0"
  deposit-contract-address = "${p.depositContract}"

  sync {
    do-snap-sync = false
  }

  pow-target-time = null

  # Every block fork is active at genesis (the script rejects any other value). "0" and the 10^18 sentinel
  # are both filtered by ForkId.gatherBlockForks, so the checksum chain reaches the timestamp forks.
  frontier-block-number = "0"
  homestead-block-number = "0"
  eip106-block-number = "1000000000000000000"
  eip150-block-number = "0"
  eip155-block-number = "0"
  eip160-block-number = "0"
  eip161-block-number = "0"
  max-code-size = "24576"
  difficulty-bomb-pause-block-number = "1000000000000000000"
  difficulty-bomb-continue-block-number = "1000000000000000000"
  difficulty-bomb-removal-block-number = "1000000000000000000"
  byzantium-block-number = "0"
  constantinople-block-number = "0"
  petersburg-block-number = "0"
  istanbul-block-number = "0"
  muir-glacier-block-number = "1000000000000000000"
  berlin-block-number = "0"

  # ETC-specific forks (disabled)
  atlantis-block-number = "1000000000000000000"
  agharta-block-number = "1000000000000000000"
  phoenix-block-number = "1000000000000000000"
  ecip1099-block-number = "1000000000000000000"
  magneto-block-number = "1000000000000000000"
  mystique-block-number = "1000000000000000000"
  spiral-block-number = "1000000000000000000"

  # London (EIP-1559) from genesis. MUST be "0", not the 10^18 sentinel (see plataberget-chain.conf).
  olympia-block-number = "0"
  olympia-gas-limit-elasticity = 2
  treasury-address = "0000000000000000000000000000000000000000"
  account-start-nonce = "0"

  custom-genesis-file = { include required("ephemery-genesis.json") }

  monetary-policy {
    first-era-block-reward = "0"
    first-era-reduced-block-reward = "0"
    first-era-constantinople-reduced-block-reward = "0"
    era-duration = 2000000000
    reward-reduction-rate = 0
  }

  gas-tie-breaker = false
  eth-compatible-storage = true

  bootstrap-nodes = [
${bootnodes(p)}  ]

  mess {
    enabled = false
  }
}
"""
