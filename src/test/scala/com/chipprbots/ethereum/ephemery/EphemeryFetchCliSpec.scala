import com.chipprbots.ethereum.testing.Tags.*

/** `fukuii cli ephemery-fetch --from-dir DIR --out DIR`: the layout of `fetch-genesis.sh`, its exit codes, and the
  * `release.json` it adds. The command never reads the system clock: the tests give it a fixed one.
  */
class EphemeryFetchCliSpec extends AnyFlatSpec with Matchers with BeforeAndAfterEach:

  private val fixedNow = Instant.parse("2026-11-12T10:00:00Z")
  private val clock = Clock.fixed(fixedNow, ZoneOffset.UTC)

  private var tmp: Path = scala.compiletime.uninitialized

  override def beforeEach(): Unit = tmp = Files.createTempDirectory("eph-fetch-cli-test")

  override def afterEach(): Unit = deleteTree(tmp)

  private def deleteTree(p: Path): Unit =
    if Files.exists(p, java.nio.file.LinkOption.NOFOLLOW_LINKS) then
      if Files.isDirectory(p, java.nio.file.LinkOption.NOFOLLOW_LINKS) then
        Files.list(p).iterator().asScala.toList.foreach(deleteTree)
      Files.delete(p)

  final private case class Run(code: Int, out: String, err: String)

  private def run(args: String*): Run =
    val out = new ByteArrayOutputStream
    val err = new ByteArrayOutputStream
    val code = EphemeryFetchCli.main(
      args.toSeq,
      Map.empty,
      clock,
      "fukuii test",
      new PrintStream(out, true, "UTF-8"),
      new PrintStream(err, true, "UTF-8")
    )
    Run(code, out.toString("UTF-8"), err.toString("UTF-8"))

  private def read(p: Path): String = new String(Files.readAllBytes(p), StandardCharsets.UTF_8)

  private def raw165: String = releaseDir(165).toString

  "ephemery-fetch --from-dir --out" should "write the layout the script wrote, plus release.json" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    val r = run("--from-dir", raw165, "--out", out.toString)
    withClue(r.err)(r.code shouldBe 0)

    val dest = out.resolve("ephemery-165")
    List("testnet", "chains", "conf").foreach(d => Files.isDirectory(dest.resolve(d)) shouldBe true)
    List(
      "release.env",
      "release.json",
      "chains/ephemery-chain.conf",
      "chains/ephemery-genesis.json",
      "conf/ephemery.conf"
    )
      .foreach(f => Files.isRegularFile(dest.resolve(f)) shouldBe true)
    Files.isSymbolicLink(out.resolve("current")) shouldBe true
    Files.readSymbolicLink(out.resolve("current")).toString shouldBe "ephemery-165"
    Files.isRegularFile(out.resolve("ephemery-local.conf")) shouldBe true
    // the members of the release, verbatim
    List("genesis.json", "retention.vars", "deposit_contract_block_hash.txt", "enodes.txt", "boot_enr.txt")
      .foreach(f => read(dest.resolve("testnet").resolve(f)) shouldBe read(releaseDir(165).resolve(f)))
    // the chain files are the committed fixtures
    read(dest.resolve("chains/ephemery-chain.conf")) shouldBe fixture(165, "ephemery-chain.conf")
    read(dest.resolve("chains/ephemery-genesis.json")) shouldBe fixture(165, "ephemery-genesis.json")
    // no stage directory is left behind
    Files.list(out).iterator().asScala.map(_.getFileName.toString).filter(_.startsWith(".stage")).toList shouldBe empty
  }

  it should "write release.env with the script's keys, and print them" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    val r = run("--from-dir", raw165, "--out", out.toString)
    val dest = out.resolve("ephemery-165")
    val env = read(dest.resolve("release.env"))
    env should startWith("# GENERATED by scripts/ephemery/fetch-genesis.sh\n")
    val keys = env.linesIterator.filterNot(_.startsWith("#")).map(_.takeWhile(_ != '=')).toList
    keys shouldBe List(
      "ITERATION",
      "RELEASE",
      "CHAIN_ID",
      "GENESIS_TIMESTAMP",
      "RESET_TIME",
      "GENESIS_HASH",
      "OUT_DIR",
      "TESTNET_DIR",
      "CHAINS_DIR",
      "FUKUII_CONF_DIR",
      "BOOTNODE_ENR_LIST"
    )
    env should include("ITERATION=\"165\"")
    env should include("RESET_TIME=\"1795114800\"")
    env should include(s"GENESIS_HASH=\"$Hash165\"")
    env should include(s"CHAINS_DIR=\"$dest/chains\"")
    r.out shouldBe env.linesIterator.filterNot(_.startsWith("#")).mkString("", "\n", "\n")
    r.err should include("next reset: 2026-11-19T19:00:00Z")
  }

  it should "write release.json that the codec reads back, with the fixed clock" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    run("--from-dir", raw165, "--out", out.toString).code shouldBe 0
    val meta = ReleaseMetadata.decode(read(out.resolve("ephemery-165/release.json"))).fold(e => fail(e), identity)
    meta.release shouldBe "ephemery-165"
    meta.iteration shouldBe 165
    meta.chainId shouldBe BigInt(39438165)
    meta.genesisTimestamp shouldBe 1792695600L
    meta.resetTime shouldBe 1795114800L
    meta.genesisHash shouldBe Hash165
    meta.archiveSha256 shouldBe None
    meta.producedBy shouldBe "fukuii test"
    meta.producedAt shouldBe fixedNow
    meta.source shouldBe releaseDir(165).toAbsolutePath.normalize.toString
  }

  it should "record the source and archive hash the wrapper script passes" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    val sha = "ab" * 32
    val url = "https://github.com/ephemery-testnet/ephemery-genesis/releases/tag/ephemery-165"
    run(
      "--from-dir",
      raw165,
      "--out",
      out.toString,
      "--release",
      "ephemery-165",
      "--source",
      url,
      "--archive-sha256",
      sha
    ).code shouldBe 0
    val meta = ReleaseMetadata.decode(read(out.resolve("ephemery-165/release.json"))).fold(e => fail(e), identity)
    meta.source shouldBe url
    meta.archiveSha256 shouldBe Some(sha)
  }

  it should "keep an existing datadir and the operator's ephemery-local.conf when run again" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    run("--from-dir", raw165, "--out", out.toString).code shouldBe 0
    val data = out.resolve("ephemery-165/data")
    Files.createDirectories(data)
    Files.write(data.resolve("keep"), "x".getBytes(StandardCharsets.UTF_8))
    Files.write(out.resolve("ephemery-local.conf"), "# mine\n".getBytes(StandardCharsets.UTF_8))
    run("--from-dir", raw165, "--out", out.toString).code shouldBe 0
    read(data.resolve("keep")) shouldBe "x"
    read(out.resolve("ephemery-local.conf")) shouldBe "# mine\n"
  }

  it should "move current to the newest release written" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    run("--from-dir", releaseDir(164).toString, "--out", out.toString).code shouldBe 0
    run("--from-dir", raw165, "--out", out.toString).code shouldBe 0
    Files.readSymbolicLink(out.resolve("current")).toString shouldBe "ephemery-165"
    Files.isDirectory(out.resolve("ephemery-164/chains")) shouldBe true
  }

  it should "refuse, with exit 1 and nothing written, a current that is not a symlink" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    Files.createDirectories(out.resolve("current"))
    val r = run("--from-dir", raw165, "--out", out.toString)
    r.code shouldBe 1
    r.err should include("exists and is not a symlink")
    Files.exists(out.resolve("ephemery-165")) shouldBe false
  }

  it should "exit 2 on a usage error" taggedAs (UnitTest) in {
    run().code shouldBe 2
    run("--from-dir", raw165).code shouldBe 2 // --out is required in this slice
    run("--out", tmp.toString).code shouldBe 2
    run("--from-dir", raw165, "--out", tmp.resolve("a\"b").toString).code shouldBe 2
    run("--from-dir", raw165, "--out", tmp.resolve("a$b").toString).code shouldBe 2
    run("--from-dir", raw165, "--out", tmp.toString, "--release", "165").code shouldBe 2
    run("--from-dir", raw165, "--out", tmp.toString, "--archive-sha256", "xyz").code shouldBe 2
    run("--from-dir", raw165, "--out", tmp.toString, "--source", "http://example.org/x").code shouldBe 2
    run("--from-dir", raw165, "--out", tmp.toString, "--bogus").code shouldBe 2
    val r = run("--from-dir", raw165, "--out", tmp.resolve("a\\b").toString)
    r.code shouldBe 2
    r.err should include("--out must not contain")
  }

  it should "exit 0 and print the usage for --help" taggedAs (UnitTest) in {
    val r = run("--help")
    r.code shouldBe 0
    r.out should include("--from-dir")
  }

  it should "exit with the class of a refusal: 78, writing nothing" taggedAs (UnitTest) in {
    val bad = tmp.resolve("bad")
    Files.createDirectories(bad)
    val broken = raw(165).editConfig(_.set("bpo3Time", num(1795114800L)))
    Files.write(bad.resolve("genesis.json"), broken.genesisJson.getBytes(StandardCharsets.UTF_8))
    List("retention.vars", "deposit_contract_block_hash.txt").foreach(f =>
      Files.copy(releaseDir(165).resolve(f), bad.resolve(f))
    )
    val out = tmp.resolve("out")
    val r = run("--from-dir", bad.toString, "--out", out.toString)
    r.code shouldBe 78
    r.err should include("genesis config declares keys fukuii cannot map: bpo3Time")
    Files.exists(out.resolve("ephemery-165")) shouldBe false
  }

  it should "exit 78 for a directory that is not a release, and for a --release that is another one" taggedAs (
    UnitTest
  ) in {
    val r = run("--from-dir", tmp.toString, "--out", tmp.resolve("out").toString)
    r.code shouldBe 78
    r.err should include("has no genesis.json")
    val wrong = run("--from-dir", raw165, "--out", tmp.resolve("out2").toString, "--release", "ephemery-164")
    wrong.code shouldBe 78
    wrong.err should include("--release ephemery-164 disagrees")
    run("--from-dir", tmp.resolve("missing").toString, "--out", tmp.resolve("out3").toString).code shouldBe 78
  }

  it should "refuse an --out inside the --from-dir, which would copy itself" taggedAs (UnitTest) in {
    val src = tmp.resolve("src")
    Files.createDirectories(src)
    List("genesis.json", "retention.vars", "deposit_contract_block_hash.txt").foreach(f =>
      Files.copy(releaseDir(165).resolve(f), src.resolve(f))
    )
    val r = run("--from-dir", src.toString, "--out", src.resolve("out").toString)
    r.code shouldBe 1
    r.err should include("is inside --from-dir")
  }
