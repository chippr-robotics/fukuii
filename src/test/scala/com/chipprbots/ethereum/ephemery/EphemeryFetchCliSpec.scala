/** `fukuii cli ephemery-fetch --from-dir DIR --out DIR`: the layout of `fetch-genesis.sh`, its exit codes, and the
  * `release.json` it adds. The command never reads the system clock: the tests give it a fixed one.
  */
class EphemeryFetchCliSpec extends AnyFlatSpec with Matchers with BeforeAndAfterEach:

  private val fixedNow = Instant.parse("2026-11-12T10:00:00Z")
  private val clock = Clock.fixed(fixedNow, ZoneOffset.UTC)

  private var tmp: Path = scala.compiletime.uninitialized

  override def beforeEach(): Unit = tmp = Files.createTempDirectory("eph-fetch-cli-test")

  override def afterEach(): Unit = deleteTree(tmp)

  private def deleteTree(p: Path): Unit =
    if Files.exists(p, java.nio.file.LinkOption.NOFOLLOW_LINKS) then
      if Files.isDirectory(p, java.nio.file.LinkOption.NOFOLLOW_LINKS) then
        Files.list(p).iterator().asScala.toList.foreach(deleteTree)
      Files.delete(p)

  final private case class Run(code: Int, out: String, err: String)

  private def run(args: String*): Run =
    val out = new ByteArrayOutputStream
    val err = new ByteArrayOutputStream
    val code = EphemeryFetchCli.main(
      args.toSeq,
      Map.empty,
      clock,
      "fukuii test",
      new PrintStream(out, true, "UTF-8"),
      new PrintStream(err, true, "UTF-8")
    )
    Run(code, out.toString("UTF-8"), err.toString("UTF-8"))

  private def read(p: Path): String = new String(Files.readAllBytes(p), StandardCharsets.UTF_8)

  private def raw165: String = releaseDir(165).toString

  "ephemery-fetch --from-dir --out" should "write the layout the script wrote, plus release.json" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    val r = run("--from-dir", raw165, "--out", out.toString)
    withClue(r.err)(r.code shouldBe 0)

    val dest = out.resolve("ephemery-165")
    List("testnet", "chains", "conf").foreach(d => Files.isDirectory(dest.resolve(d)) shouldBe true)
    List(
      "release.env",
      "release.json",
      "chains/ephemery-chain.conf",
      "chains/ephemery-genesis.json",
      "conf/ephemery.conf"
    )
      .foreach(f => Files.isRegularFile(dest.resolve(f)) shouldBe true)
    Files.isSymbolicLink(out.resolve("current")) shouldBe true
    Files.readSymbolicLink(out.resolve("current")).toString shouldBe "ephemery-165"
    Files.isRegularFile(out.resolve("ephemery-local.conf")) shouldBe true
    // the members of the release, verbatim
    List("genesis.json", "retention.vars", "deposit_contract_block_hash.txt", "enodes.txt", "boot_enr.txt")
      .foreach(f => read(dest.resolve("testnet").resolve(f)) shouldBe read(releaseDir(165).resolve(f)))
    // the chain files are the committed fixtures
    read(dest.resolve("chains/ephemery-chain.conf")) shouldBe fixture(165, "ephemery-chain.conf")
    read(dest.resolve("chains/ephemery-genesis.json")) shouldBe fixture(165, "ephemery-genesis.json")
    // no stage directory is left behind
    Files.list(out).iterator().asScala.map(_.getFileName.toString).filter(_.startsWith(".stage")).toList shouldBe empty
  }

  it should "write release.env with the script's keys, and print them" taggedAs (UnitTest) in {
    val out = tmp.resolve("out")
    val r = run("--from-dir", raw165, "--out", out.toString)
