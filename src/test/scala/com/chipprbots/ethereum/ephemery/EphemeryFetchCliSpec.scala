    env should include(s"CHAINS_DIR=\"$dest/chains\"")
    r.out shouldBe env.linesIterator.filterNot(_.startsWith("#")).mkString("", "\n", "\n")
    r.err should include("next reset: 2026-11-19T19:00:00Z")
  }

