#!/usr/bin/env python3
"""Generate and check specs/README.md, the index of every Spec Kit feature under specs/.

Source of truth is each spec's header (see docs/development/spec-lifecycle.md):

    **Status**: <Word> (<YYYY-MM-DD>). <one sentence>
    **In flight**: <branch, PR or session>            (optional)
    **Release**: <version>                             (optional)

<Word> is one of the fixed vocabulary below; "Superseded by NNN" names the superseding spec.

Usage:
    scripts/specs/index.py            # rewrite specs/README.md
    scripts/specs/index.py --check    # exit 1 if a header is invalid or the README is stale (CI)

Standard library only. Deterministic output.
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPECS = ROOT / "specs"
README = SPECS / "README.md"

OPEN = ("Draft", "Clarified", "Planned", "Active")
CLOSED = ("Done", "Superseded", "Parked", "Withdrawn")
VOCAB = OPEN + CLOSED

STATUS_RE = re.compile(r"^\*{0,2}Status\*{0,2}:\s*(.+?)\s*$", re.M)
WORD_RE = re.compile(
    r"^\**\s*(Draft|Clarified|Planned|Active|Done|Superseded by (\d{3})|Parked|Withdrawn)\b\**"
)
DATE_RE = re.compile(r"\b(\d{4}-\d{2}-\d{2})\b")
INFLIGHT_RE = re.compile(r"^\*\*In flight\*\*:\s*(.+?)\s*$", re.M)
RELEASE_RE = re.compile(r"^\*\*Release\*\*:\s*(.+?)\s*$", re.M)
TITLE_RE = re.compile(r"^#\s+(?:Feature Specification:\s*)?(.+?)\s*$", re.M)
DONE_BOX = re.compile(r"^\s*- \[x\]", re.M | re.I)
OPEN_BOX = re.compile(r"^\s*- \[ \]", re.M)


@dataclass
class Spec:
    number: str
    dirname: str
    title: str
    word: str
    superseded_by: str | None
    date: str
    sentence: str
    in_flight: str
    release: str
    tasks_done: int | None
    tasks_open: int | None
    errors: list[str]

    @property
    def is_open(self) -> bool:
        return self.word in OPEN

    @property
    def status_cell(self) -> str:
        if self.word == "Superseded":
            return f"Superseded by [{self.superseded_by}](./{_dir_for(self.superseded_by)}/spec.md)"
        return self.word


def _dir_for(number: str) -> str:
    for d in sorted(SPECS.iterdir()):
        if d.is_dir() and d.name.startswith(number + "-"):
            return d.name
    return number


def parse(spec_dir: Path) -> Spec:
    errors: list[str] = []
    text = (spec_dir / "spec.md").read_text(encoding="utf-8")
    number = spec_dir.name[:3]
    m = TITLE_RE.search(text)
    title = m.group(1) if m else spec_dir.name
    # Spec 011/012 style titles ("011 - Evict ...") carry the number; drop it.
    title = re.sub(r"^\d{3}\s*-\s*", "", title)

    word, superseded_by, date, sentence = "", None, "", ""
    sm = STATUS_RE.search(text)
    if not sm:
        errors.append("no `**Status**:` line")
    else:
        status = sm.group(1)
        wm = WORD_RE.match(status)
        if not wm:
            errors.append(f"status does not start with one of {', '.join(VOCAB)}: {status[:60]!r}")
        else:
            word = "Superseded" if wm.group(1).startswith("Superseded") else wm.group(1)
            superseded_by = wm.group(2)
            rest = status[wm.end():]
            dm = DATE_RE.search(rest)
            date = dm.group(1) if dm else ""
            if not dm:
                errors.append("status line has no YYYY-MM-DD date")
            sentence = re.sub(r"^[\s\*\.\(\)\-—:]*(\d{4}-\d{2}-\d{2})?[\s\*\.\)\-—:]*", "", rest).strip()
            if superseded_by and not any(
                d.is_dir() and d.name.startswith(superseded_by + "-") for d in SPECS.iterdir()
            ):
                errors.append(f"superseded by {superseded_by}, which does not exist under specs/")

    fm = INFLIGHT_RE.search(text)
    in_flight = fm.group(1) if fm else ""
    rm = RELEASE_RE.search(text)
    release = rm.group(1) if rm else ""

    tasks = spec_dir / "tasks.md"
    tasks_done = tasks_open = None
    if tasks.exists():
        t = tasks.read_text(encoding="utf-8")
        tasks_done, tasks_open = len(DONE_BOX.findall(t)), len(OPEN_BOX.findall(t))

    return Spec(number, spec_dir.name, title, word, superseded_by, date, sentence, in_flight, release,
                tasks_done, tasks_open, errors)


def load() -> list[Spec]:
    dirs = sorted(d for d in SPECS.iterdir() if d.is_dir() and re.match(r"^\d{3}-", d.name))
    return [parse(d) for d in dirs if (d / "spec.md").exists()]


def _cell(s: str) -> str:
    return s.replace("|", "\\|") if s else "—"


def _tasks(sp: Spec) -> str:
    if sp.tasks_done is None:
        return "—"
    return f"{sp.tasks_done} / {sp.tasks_open}"


def render(specs: list[Spec]) -> str:
    out: list[str] = []
    out.append("# Specs index")
    out.append("")
    out.append("<!-- GENERATED by scripts/specs/index.py from each spec's header. Do not edit by hand: run")
    out.append("     `python3 -I scripts/specs/index.py` and commit the result. CI runs `--check`. -->")
    out.append("")
    out.append("Lifecycle, vocabulary and closure procedure: [docs/development/spec-lifecycle.md]"
               "(../docs/development/spec-lifecycle.md). Directories are never moved or renumbered; the Spec Kit")
    out.append("scripts allocate the next number from the highest `NNN-` prefix present here.")
    out.append("")
    opened = [s for s in specs if s.is_open]
    closed = [s for s in specs if not s.is_open]
    invalid = [s for s in specs if s.errors]
    counts = ", ".join(f"{w} {sum(1 for s in specs if s.word == w)}" for w in VOCAB if any(s.word == w for s in specs))
    out.append(f"**{len(specs)} specs**: {counts}.")
    out.append("")
    out.append("## Open")
    out.append("")
    out.append("Tasks are `done / open` boxes in `tasks.md`; a closed spec keeps its boxes as they were at closure.")
    out.append("")
    out.append("| Spec | Title | Status | Since | Release | Tasks | In flight | Note |")
    out.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for s in opened + invalid:
        if s in opened or s.word == "":
            status = s.status_cell if s.word else "**INVALID HEADER**"
            out.append(f"| [{s.number}](./{s.dirname}/spec.md) | {_cell(s.title)} | {status} | {_cell(s.date)} | "
                       f"{_cell(s.release)} | {_tasks(s)} | {_cell(s.in_flight)} | {_cell(s.sentence)} |")
    out.append("")
    out.append("## Closed")
    out.append("")
    out.append("| Spec | Title | Status | Since | Release | Tasks at closure | Note |")
    out.append("| --- | --- | --- | --- | --- | --- | --- |")
    for s in closed:
        out.append(f"| [{s.number}](./{s.dirname}/spec.md) | {_cell(s.title)} | {s.status_cell} | {_cell(s.date)} | "
                   f"{_cell(s.release)} | {_tasks(s)} | {_cell(s.sentence)} |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    specs = load()
    problems = [(s.dirname, e) for s in specs for e in s.errors]
    rendered = render(specs)
    if check:
        for d, e in problems:
            print(f"specs/{d}/spec.md: {e}", file=sys.stderr)
        current = README.read_text(encoding="utf-8") if README.exists() else ""
        stale = current != rendered
        if stale:
            print("specs/README.md is stale: run `python3 -I scripts/specs/index.py` and commit it.", file=sys.stderr)
        return 1 if (problems or stale) else 0
    README.write_text(rendered, encoding="utf-8")
    for d, e in problems:
        print(f"WARNING specs/{d}/spec.md: {e}", file=sys.stderr)
    print(f"wrote {README.relative_to(ROOT)} ({len(specs)} specs, {len(problems)} header problems)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
